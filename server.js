const express = require("express");
const OpenAI = require("openai");
const path = require("path");
require("dotenv").config();

const app = express();

const openai = new OpenAI({
    apiKey: process.env.OPENAI_API_KEY
});

app.use(express.json({ limit: "20kb" }));

app.use(express.static(path.join(__dirname, "public")));


/*
====================================================
  موتور اصلی حاضرجوابی
====================================================
*/

app.post("/api/reply", async (req, res) => {

    try {

        const message =
            typeof req.body.message === "string"
                ? req.body.message.trim()
                : "";

        const style =
            typeof req.body.style === "string"
                ? req.body.style
                : "sigma";


        if (!message) {

            return res.status(400).json({
                error: "پیام خالی است."
            });

        }


        const styles = {

            sigma: `
جواب سیگما:
خونسرد، بااعتمادبه‌نفس، کوتاه و حاضرجواب.
نه التماس، نه عصبانیت، نه توهین سنگین.
`,

            kind: `
جواب مهربان:
حاضرجواب ولی دوستانه و نرم.
`,

            funny: `
جواب خنده‌دار:
حاضرجواب، بامزه و شوخ.
`,

            cool: `
جواب خفن:
بااعتمادبه‌نفس، جذاب و محکم.
`,

            polite: `
جواب محترمانه:
حاضرجواب ولی کاملاً مؤدبانه.
`,

            short: `
جواب کوتاه:
خیلی کوتاه، ترجیحاً یک جمله.
`
        };


        const selectedStyle =
            styles[style] || styles.sigma;


        const instructions = `
تو موتور هوش مصنوعی سایت «🗿 Sigma Reply» هستی.

وظیفه اصلی تو «حاضرجوابی» است.

کاربر پیام شخص دیگری را به تو می‌دهد.
تو نباید آن پیام را مثل یک سؤال معمولی پاسخ علمی یا آموزشی بدهی.

باید یک جواب حاضرجواب و مناسب برای همان پیام بسازی.

مثال:

پیام:
«تو چقدر مهربونی»

جواب مناسب:
«بالاخره یکی متوجه شد 😎»

---

پیام:
«تو خیلی ادعایی»

جواب مناسب:
«ادعا نیست، فقط لازم نیست همه‌چیو ثابت کنم 🗿»

---

پیام:
«فکر کردی خیلی خفنی؟»

جواب مناسب:
«نه، فقط برای خفن بودن دنبال تأیید نیستم 😎»

---

پیام:
«تو هیچی نیستی»

جواب مناسب:
«پس چرا هنوز داری درباره من حرف می‌زنی؟ 🗿»

---

پیام:
«مگه کی هستی؟»

جواب مناسب:
«همون کسی که هنوز داری وقت می‌ذاری درباره‌ش حرف بزنی 😎»

قوانین:

1. همیشه مستقیماً به همان پیام واکنش نشان بده.
2. موضوع و منظور پیام را بفهم.
3. جواب نباید بی‌ربط یا عمومی باشد.
4. اگر طرف تعریف کرده، جواب حاضرجواب متناسب با همان تعریف بده.
5. اگر طرف مسخره کرده، جواب حاضرجواب متناسب با همان حرف بده.
6. اگر طرف طعنه زده، طعنه را بفهم و جواب متناسب بساز.
7. اگر طرف چالش کرده، جواب محکم و حاضرجواب بده.
8. اگر طرف سؤال معمولی پرسیده ولی هدف سایت حاضرجوابی است، یک جواب حاضرجواب به خود سؤال/حرف بده، نه یک پاسخ مقاله‌ای.
9. جواب را فارسی بنویس.
10. جواب معمولاً یک جمله باشد.
11. از فحش سنگین، تهدید یا توهین شدید استفاده نکن.
12. جواب نباید طرف مقابل را به آسیب یا کار خطرناک تشویق کند.
13. از کلیشه‌هایی مثل «هر حرفی جواب ندارد» مگر وقتی واقعاً مناسب متن است استفاده نکن.
14. هر بار جواب تازه و متناسب با متن بساز.
15. فقط خود جواب را برگردان؛ توضیح نده.

سبک انتخاب‌شده:
${selectedStyle}
`;


        const response =
            await openai.responses.create({

                model: "gpt-5.5",

                instructions: instructions,

                input: message,

                max_output_tokens: 100

            });


        const answer =
            response.output_text?.trim();


        if (!answer) {

            return res.status(500).json({
                error: "پاسخی دریافت نشد."
            });

        }


        res.json({
            answer: answer
        });


    } catch (error) {

        console.error(error);

        res.status(500).json({
            error: "خطا در اتصال به هوش مصنوعی."
        });

    }

});


const PORT =
    process.env.PORT || 3000;


app.listen(PORT, () => {

    console.log(
        `🗿 Sigma Reply running on port ${PORT}`
    );

});
